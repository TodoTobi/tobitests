class IngestError(Exception):
    def __init__(self, code: int, message: str = ""):
        super().__init__(message)
        self.code = code


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug or "tobitests"


def _preflight(url: str, timeout: float = 3.0) -> bool:
    """True si hay CUALQUIER respuesta HTTP (aun 404); False si no conecta."""
    import urllib.error
    import urllib.request

    try:
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "TobiTests-Preflight/1.0"},
        )
        with urllib.request.urlopen(req, timeout=timeout):
            return True
    except urllib.error.HTTPError:
        return True
    except Exception:
        return False


def state_path(repo_root: Path, slug: str) -> Path:
    """Devuelve la ruta canónica del archivo de estado según el Paso 0."""
    return repo_root / "web" / "public" / "data" / f"{slug}-state.json"

def atomic_write_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = path.parent / f".{path.name}.{os.getpid()}.{time.time_ns()}.tmp"
    try:
        tmp_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        os.replace(tmp_path, path)
    except Exception:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except Exception:
                pass
        raise


def locked_update(path: Path, fn: Callable[[Dict[str, Any]], Dict[str, Any]]) -> Dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    lock_path = Path(f"{str(path)}.lock")

    lock_acquired = False
    for attempt in range(5):
        try:
            if lock_path.exists() and (time.time() - lock_path.stat().st_mtime > 10):
                try:
                    lock_path.unlink()
                except Exception:
                    pass
        except OSError:
            pass

        try:
            fd = os.open(str(lock_path), os.O_CREAT | os.O_EXCL | os.O_RDWR)
            os.close(fd)
            lock_acquired = True
            break
        except FileExistsError:
            if attempt < 4:
                time.sleep(0.1)

    try:
        data: Dict[str, Any] = {}
        if path.exists():
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except Exception:
                data = {}

        updated = fn(data)
        atomic_write_json(path, updated)
        return updated
    finally:
        if lock_acquired and lock_path.exists():
            try:
                lock_path.unlink()
            except Exception:
                pass


ALLOWED_SEVERITIES = {
    "critical",
    "high",
    "medium",
    "low",
    "Critical",
    "High",
    "Medium",
    "Low",
    "Crítica",
    "Alta",
    "Media",
    "Baja",
}

ALLOWED_STATUSES = {"Confirmed", "Resolved", "Closed"}


def validate_bug_report(
    bug: Dict[str, Any],
    repo_root: Optional[Path] = None,
) -> Tuple[bool, List[str]]:
    """Valida que un reporte de bug cumpla con el contrato canónico BugItem."""
    errors: List[str] = []
    if not isinstance(bug, dict):
        return False, ["Bug report must be a dictionary"]

    mandatory_str_keys = [
        "id",
        "title",
        "severity",
        "status",
        "section",
        "runId",
        "agent",
        "dadoQue",
        "cuando",
        "entonces",
    ]
    for key in mandatory_str_keys:
        if key not in bug:
            errors.append(f"Missing mandatory field: '{key}'")
        else:
            val = bug[key]
            if not isinstance(val, str) or not val.strip():
                errors.append(f"Field '{key}' must be a non-empty string")

    sev = bug.get("severity")
    if sev is not None and sev not in ALLOWED_SEVERITIES:
        errors.append(f"Invalid severity '{sev}'. Allowed: {sorted(ALLOWED_SEVERITIES)}")

    st = bug.get("status")
    if st is not None and st not in ALLOWED_STATUSES:
        errors.append(f"Invalid status '{st}'. Allowed: {sorted(ALLOWED_STATUSES)}")

    if "gherkin" in bug and bug["gherkin"] is not None:
        gh = bug["gherkin"]
        if not isinstance(gh, dict):
            errors.append("Field 'gherkin' must be a dictionary")
        else:
            for g_key in ("given", "when", "then"):
                g_val = gh.get(g_key)
                if not isinstance(g_val, str) or not g_val.strip():
                    errors.append(f"Field 'gherkin.{g_key}' must be a non-empty string")

    if "diagnostic" in bug and bug["diagnostic"] is not None:
        diag = bug["diagnostic"]
        if not isinstance(diag, dict):
            errors.append("Field 'diagnostic' must be a dictionary")
        else:
            for d_key in ("observedFact", "whiteBoxHypothesis", "reproductionSpec", "affectedFile"):
                d_val = diag.get(d_key)
                if not isinstance(d_val, str):
                    errors.append(f"Field 'diagnostic.{d_key}' must be a string")

    # White-Box Validation (Hallazgo C7)
    line_val = bug.get("root_cause_line")
    if line_val is not None:
        if not isinstance(line_val, int) or isinstance(line_val, bool):
            errors.append("Field 'root_cause_line' must be an integer")
        elif line_val < 0:
            errors.append(f"Field 'root_cause_line' must be >= 0 (got {line_val})")

    rc_file = bug.get("root_cause_file")
    if repo_root is not None and rc_file and isinstance(rc_file, str) and rc_file.strip():
        target_path = Path(repo_root) / rc_file
        if target_path.is_file():
            try:
                total_lines = len(target_path.read_text(encoding="utf-8", errors="replace").splitlines())
            except Exception:
                total_lines = 0

            if line_val is not None and isinstance(line_val, int) and not isinstance(line_val, bool):
                if line_val < 1 or line_val > total_lines:
                    errors.append(
                        f"root_cause_line {line_val} is out of range for existing file '{rc_file}' (1-{total_lines})"
                    )

    return (len(errors) == 0, errors)


def synthesize_draft_bug(
    test_item: Dict[str, Any],
    run_id: str,
    bug_id: str,
    repo_root: Optional[Path] = None,
) -> Dict[str, Any]:
    """Sintetiza un bug borrador auto-generado a partir de un test fallido."""
    t = test_item
    t_name = str(t.get("name", "Unnamed Test"))
    spec_name = str(t.get("spec", "Playwright Suite"))

    ev = t.get("evidence") or {}
    page_errors = t.get("pageErrors") or []
    console_log = ev.get("console_log") or []
    network_trace = ev.get("network_trace") or []
    has_layer1 = bool(page_errors) or any("error" in str(x).lower() for x in console_log) or any(
        "500" in str(x) or "400" in str(x) for x in network_trace
    )
    oracle_layer = "Layer 1: Implicit" if has_layer1 else "Layer 2: State Divergence"

    steps = t.get("steps") or []
    failed_step = next((s for s in steps if isinstance(s, dict) and s.get("status") == "Failed"), None)
    if failed_step:
        st_num = failed_step.get("step", 1)
        st_act = failed_step.get("action", "Action")
        st_tgt = failed_step.get("target", "Target")
        cuando = f"ejecuta el paso #{st_num}: {st_act} ({st_tgt})"
    else:
        cuando = "ejecuta las aserciones del test"

    error_obj = t.get("error")
    error_msg = ""
    if isinstance(error_obj, dict):
        error_msg = error_obj.get("message", "")
    elif isinstance(error_obj, str):
        error_msg = error_obj

    if error_msg and error_msg.strip():
        entonces = error_msg.strip()[:300]
    elif failed_step and failed_step.get("actual"):
        entonces = str(failed_step.get("actual")).strip()[:300]
    else:
        entonces = "el test falló durante la ejecución"

    dado_que = f"el suite Playwright ejecuta la especificación {spec_name}"

    err_loc = error_obj.get("location", {}) if isinstance(error_obj, dict) else {}
    rc_file = err_loc.get("file", "") or f"specs/{spec_name}"
    raw_line = err_loc.get("line", 1)
    try:
        rc_line = int(raw_line) if raw_line is not None else 1
    except (ValueError, TypeError):
        rc_line = 1
    if rc_line <= 0:
        rc_line = 1

    nearby = error_obj.get("nearby", []) if isinstance(error_obj, dict) else []
    if nearby and isinstance(nearby, list):
        wb_hyp = "; ".join(str(x) for x in nearby[:3])
    else:
        wb_hyp = "Fallo de aserción o timeout detectado por el runner de Playwright."

    diag = {
        "observedFact": entonces,
        "whiteBoxHypothesis": wb_hyp,
        "reproductionSpec": f"specs/{spec_name} ({t_name})",
        "affectedFile": f"{rc_file}:{rc_line}",
        "recommendedFix": "Inspeccionar el error y la traza cercana en el modal de diagnóstico para corregir la divergencia.",
        "scopeIn": [f"specs/{spec_name}"],
        "scopeOut": ["package.json", "playwright.config.ts"],
    }

    now_date = datetime.datetime.now().strftime("%d/%m/%Y")
    test_key = f"{spec_name}::{t_name}"

    draft_bug = {
        "id": bug_id,
        "title": f"Fallo en {t_name}",
        "severity": "high",
        "priority": "P1",
        "oracle_layer": oracle_layer,
        "status": "Confirmed",
        "section": spec_name,
        "runId": run_id,
        "agent": "Telemetry Auditor",
        "assignee": "Unassigned",
        "date": now_date,
        "scenario": f"{bug_id}: Fallo en {t_name}, seccion: {spec_name}",
        "dadoQue": dado_que,
        "cuando": cuando,
        "entonces": entonces,
        "gherkin": {
            "given": dado_que,
            "when": cuando,
            "then": "la aserción debería cumplirse sin errores",
            "but": entonces,
        },
        "screenshot": t.get("screenshot", ""),
        "videoUrl": t.get("videoUrl", ""),
        "evidence": {
            "screenshot": t.get("screenshot", ""),
            "video": t.get("videoUrl", ""),
            "console_log": ev.get("console_log", []),
            "network_trace": ev.get("network_trace", []),
        },
        "root_cause_file": rc_file,
        "root_cause_line": rc_line,
        "diagnostic": diag,
        "autoGenerated": True,
        "testKey": test_key,
    }
    return draft_bug


def _strip_ansi(text: str) -> str:
    return re.sub(r"\x1b\[[0-9;]*[A-Za-z]", "", text)


RE_ASSERT = re.compile(r"^(?:expect\b)", re.IGNORECASE)
RE_NAVIGATE = re.compile(r"^(?:navigate\b)|(?:\.goto\(|go\s+back|go\s+forward|reload)", re.IGNORECASE)
RE_CLICK = re.compile(r"^(?:click\b|double\s+click\b|tap\b)|(?:\.click\(|\.dblclick\()", re.IGNORECASE)
RE_FILL = re.compile(r"^(?:fill\b|type\b|press\b|select\s+option\b|set\s+input\s+files\b)|(?:\.fill\(|\.type\(|\.press\()", re.IGNORECASE)
RE_HOVER = re.compile(r"^(?:hover\b)", re.IGNORECASE)
RE_CHECK = re.compile(r"^(?:check\b|uncheck\b)", re.IGNORECASE)
RE_WAIT = re.compile(r"^(?:wait\b)|(?:waitfor)", re.IGNORECASE)
RE_REQUEST = re.compile(r"^(?:GET|POST|PUT|PATCH|DELETE|HEAD)(?:\s|$|/|:|\?)", re.IGNORECASE)

RE_NOISE = re.compile(
    r"^(?:create\s+context|create\s+page|create\s+request\s+context|"
    r"close\s+context|close\s+page|close\s+browser|dispose\s+request\s+context|"
    r"launch\s+browser|attach|before\s+hooks|after\s+hooks|beforeall|afterall|fixture|worker\s+cleanup)",
    re.IGNORECASE,
)


def _classify_step(title: str, category: Optional[str] = None) -> str:
    clean_title = _strip_ansi(title).strip()
    if category == "expect" or clean_title.lower().startswith("expect") or RE_ASSERT.search(clean_title):
        return "Assert"
    if RE_NAVIGATE.search(clean_title):
        return "Navigate"
    if RE_CLICK.search(clean_title):
        return "Click"
    if RE_FILL.search(clean_title):
        return "Fill"
    if RE_HOVER.search(clean_title):
        return "Hover"
    if RE_CHECK.search(clean_title):
        return "Check"
    if "waitfortimeout" in clean_title.lower():
        return "Action"
    if RE_WAIT.search(clean_title):
        return "Wait"
    if RE_REQUEST.match(clean_title):
        return "Request"
    return "Action"


def _is_noise_step(title: str) -> bool:
    clean_title = _strip_ansi(title).strip()
    return bool(RE_NOISE.match(clean_title))


def _is_internal_step(title: str) -> bool:
    return _is_noise_step(title)



def _new_run_id(now: datetime.datetime) -> str:
    return f"#RUN-PW-{now.strftime('%Y%m%d-%H%M%S')}"


def _git_info(repo_root: Path) -> Tuple[str, str]:
    branch = "main"
    commit = "HEAD"
    try:
        res_b = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            timeout=5,
        )
        if res_b.returncode == 0 and res_b.stdout.strip():
            branch = res_b.stdout.strip()
    except Exception:
        return ("main", "HEAD")

    try:
        res_c = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            timeout=5,
        )
        if res_c.returncode == 0 and res_c.stdout.strip():
            commit = res_c.stdout.strip()
    except Exception:
        return (branch, "HEAD")

    return (branch, commit)


def _safe_copy(src: Path, dst: Path, retries: int = 3) -> bool:
    if dst.suffix == ".webm":
        try:
            if src.stat().st_size == 0:
                return False
        except OSError:
            pass

    dst.parent.mkdir(parents=True, exist_ok=True)
    for attempt in range(retries):
        try:
            shutil.copy2(src, dst)
            return True
        except Exception:
            if attempt < retries - 1:
                time.sleep(0.2)

    print(f"[TobiTests Bridge] WARNING: no se pudo copiar {src}", file=sys.stderr)
    return False


