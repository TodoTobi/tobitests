#!/usr/bin/env python3
"""
TobiTests Automatic Playwright -> UI JSON Bridge (`scripts/ingest_playwright_results.py`).

Responsibilities:
1. Optionally runs `npx playwright test` (when `--run-playwright` is passed), capturing
   the exit code without aborting so failed assertions can still be ingested and triaged.
2. Parses `test-results/report.json` generated by Playwright's JSON reporter.
3. Copies media artifacts from test attachments into versioned run directories:
   `web/public/evidence/runs/RUN-PW-<stamp>/<testSlug>/...` and
   `web/public/evidence/videos/RUN-PW-<stamp>/...`.
4. Updates `web/public/data/<project>-state.json` (and `web/src/data/<project>-state.json`
   if present, plus `workspaces/<project>/test-matrix.json`) with step timings, pass/fail/blocked
   counts, and evidence URLs.
5. Transitions the Shared Blackboard (`web/public/data/antigravity-live.json`) to
   `blackboardState: "standup_meeting"`, `currentPipelineStep: 8`, `handoffReady: true`.
"""

