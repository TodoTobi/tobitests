def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="ingest_playwright_results",
        description="TobiTests Automatic Playwright -> UI JSON Bridge & Evidence Ingestor",
    )
    parser.add_argument(
        "--project",
        type=str,
        default="tobitests",
        help="Target project slug (default: tobitests)",
    )
    parser.add_argument(
        "--report",
        type=str,
        default="test-results/report.json",
        help="Path to Playwright JSON report (default: test-results/report.json)",
    )
    parser.add_argument(
        "--scope",
        type=str,
        choices=["frontend", "backend", "fullstack"],
        default=None,
        help="Optional audit scope ('frontend', 'backend', 'fullstack') for incremental merge tagging",
    )
    parser.add_argument(
        "--run-playwright",
        action="store_true",
        help="Execute `npx playwright test` before ingesting test-results/report.json",
    )
    parser.add_argument(
        "--spec",
        type=str,
        default=None,
        help="Optional specific spec file to pass to `npx playwright test` when --run-playwright is used",
    )
    parser.add_argument(
        "--skip-preflight",
        action="store_true",
        help="Skip preflight HTTP connectivity check before running Playwright",
    )
    parser.add_argument(
        "--repo",
        type=str,
        default=None,
        help="Optional repo root directory",
    )
    args = parser.parse_args(argv)

    repo_root = Path(args.repo).resolve() if args.repo else Path(__file__).resolve().parent.parent
    project_slug = slugify(args.project)
    report_arg = Path(args.report)
    report_path = report_arg if report_arg.is_absolute() else (repo_root / report_arg)

    started = time.time()
    if args.run_playwright:
        target_state = state_path(repo_root, project_slug)
        state_data: Dict[str, Any] = {}
        if target_state.exists():
            try:
                state_data = json.loads(target_state.read_text(encoding="utf-8"))
            except Exception:
                pass

        state_url = state_data.get("project", {}).get("url")
        target_url = os.environ.get("TARGET_URL") or os.environ.get("BASE_URL") or state_url or "http://localhost:5180"

        # Check preflight
        skip = args.skip_preflight or (project_slug in ("tobitests", "tobi") and target_url == "http://localhost:5180")
        if not skip:
            if not _preflight(target_url, timeout=3.0):
                print(
                    f"[TobiTests Bridge] ERROR (code 4): app no responde en {target_url}; levantala o usá --skip-preflight",
                    file=sys.stderr,
                )
                return 4

        env = {**os.environ, "TOBI_PROJECT": project_slug}
        if "TARGET_URL" not in env and target_url:
            env["TARGET_URL"] = target_url

        cmd = ["npx", "playwright", "test"]
        if args.spec:
            cmd.append(args.spec)
        print(f"[TobiTests Bridge] Running Playwright CLI: {' '.join(cmd)}")
        proc = subprocess.run(cmd, cwd=str(repo_root), env=env, shell=(os.name == "nt"))
        print(f"[TobiTests Bridge] Playwright exited with code {proc.returncode} (proceeding with ingestion)")
        if not report_path.exists() or report_path.stat().st_mtime < started - 1:
            print(
                f"[TobiTests Bridge] ERROR (code 2): Report {report_path} is missing or stale after playwright execution",
                file=sys.stderr,
            )
            return 2
    else:
        if not report_path.exists():
            print(
                f"[TobiTests Bridge] ERROR (code 2): Report {report_path} not found",
                file=sys.stderr,
            )
            return 2

    try:
        screenshots: List[str] = []
        videos: List[str] = []
        state_file = ingest_report_into_state(
            repo_root=repo_root,
            project_slug=project_slug,
            report_path=report_path,
            copied_screenshots=screenshots,
            copied_videos=videos,
            audit_scope=args.scope,
            partial=bool(args.spec),
        )
        live_path = transition_blackboard_to_standup(repo_root, project_slug, audit_scope=args.scope)
    except IngestError as e:
        print(f"[TobiTests Bridge] ERROR (code {e.code}): {e}", file=sys.stderr)
        return e.code

    print(f"[TobiTests Bridge] Updated UI State JSON : {state_file.relative_to(repo_root)}")
    print(f"[TobiTests Bridge] Evidence linked       : {len(screenshots)} screenshots, {len(videos)} videos")
    print(f"[TobiTests Bridge] Blackboard updated    : {live_path.relative_to(repo_root)} (standup_meeting, step=8/8)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
